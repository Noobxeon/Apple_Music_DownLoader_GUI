import os
from playwright.sync_api import sync_playwright

import sys
# 定义保存 cookies 的路径，保存在上一级目录(根目录) 或者由命令行传入
COOKIES_FILE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.dirname(__file__)), 'cookies.txt')

def convert_to_netscape(playwright_cookies):
    """将 Playwright 的 Cookie 转换为 gamdl 认识的 Netscape 格式"""
    netscape_format = ""
    netscape_format += "# Netscape HTTP Cookie File\n"
    netscape_format += "# http://curl.haxx.se/docs/http-cookies.html\n"
    netscape_format += "# This file was generated by Apple Music Downloader GUI\n\n"

    for cookie in playwright_cookies:
        domain = cookie['domain']
        flag = "TRUE" if domain.startswith('.') else "FALSE"
        path = cookie['path']
        secure = "TRUE" if cookie['secure'] else "FALSE"
        expiration = str(int(cookie['expires'])) if 'expires' in cookie and cookie['expires'] > 0 else "0"
        name = cookie['name']
        value = cookie['value']

        netscape_format += f"{domain}\t{flag}\t{path}\t{secure}\t{expiration}\t{name}\t{value}\n"
    
    return netscape_format

def login_and_save_cookies():
    """弹出浏览器让用户登录，智能嗅探底层 Cookie"""
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        context = browser.new_context()
        page = context.new_page()
        
        print("正在打开 Apple Music 登录页面...")
        page.goto("https://music.apple.com/login")
        
        print("请在弹出的窗口中登录。登录成功后，程序会自动抓取 Cookie 并关闭窗口...")
        
        success = False
        # 循环检查底层数据，最长等待 5 分钟 (60次 * 5秒)
        for _ in range(60): 
            cookies = context.cookies()
            cookie_names = [c['name'] for c in cookies]
            
            # 'media-user-token' 是 Apple Music 登录成功后发放的核心通行证
            if 'media-user-token' in cookie_names: 
                print("检测到核心凭证，登录成功！")
                page.wait_for_timeout(2000) # 稍微等2秒让所有附属cookie稳定
                success = True
                break
            
            page.wait_for_timeout(5000) # 每隔5秒嗅探一次
            
        if success:
            all_cookies = context.cookies()
            netscape_cookies = convert_to_netscape(all_cookies)
            with open(COOKIES_FILE, 'w', encoding='utf-8') as f:
                f.write(netscape_cookies)
            print(f"✅ 成功！Cookie 已保存至: {COOKIES_FILE}")
        else:
            print("❌ 获取 Cookie 失败或等待超时，请重试。")
            
        browser.close()

if __name__ == "__main__":
    login_and_save_cookies()