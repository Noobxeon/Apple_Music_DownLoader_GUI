function validToken(cookie, now = Date.now() / 1000) {
  return cookie.name === 'media-user-token' && Boolean(cookie.value)
    && (cookie.domain.replace(/^\./, '') === 'music.apple.com')
    && (!cookie.expirationDate || cookie.expirationDate > now);
}

function toNetscape(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Apple Music Studio Downloader', ''];
  for (const cookie of cookies) {
    if (!/(^|\.)apple\.com$/.test(cookie.domain.replace(/^\./, ''))) continue;
    const cookieDomain = validToken(cookie) ? '.music.apple.com' : cookie.domain;
    const domain = (cookie.httpOnly ? '#HttpOnly_' : '') + cookieDomain;
    const fields = [domain, cookieDomain.startsWith('.') ? 'TRUE' : 'FALSE', cookie.path || '/',
      cookie.secure ? 'TRUE' : 'FALSE', Math.floor(cookie.expirationDate || 0), cookie.name, cookie.value];
    if (fields.some(v => /[\t\r\n]/.test(String(v)))) throw new Error('Cookie 格式无效');
    lines.push(fields.join('\t'));
  }
  return lines.join('\n') + '\n';
}

function hasValidToken(content) {
  return (content || '').split(/\r?\n/).some(line => {
    if (line.startsWith('#HttpOnly_')) line = line.slice(10);
    else if (line.startsWith('#')) return false;
    const fields = line.split('\t');
    return fields.length === 7 && validToken({
      domain: fields[0],
      name: fields[5],
      value: fields[6],
      expirationDate: Number(fields[4])
    });
  });
}

function inspectCookieContent(content, cookiePath = '') {
  if (!content) {
    return { valid: false, exists: false, hasMediaToken: false, expired: false, count: 0, expiresAt: null, path: cookiePath };
  }
  const lines = content.split(/\r?\n/);
  let count = 0;
  let hasMediaToken = false;
  let tokenExpiry = 0;
  for (let line of lines) {
    if (line.startsWith('#HttpOnly_')) line = line.slice(10);
    else if (!line.trim() || line.startsWith('#')) continue;
    const fields = line.split('\t');
    if (fields.length === 7) {
      count++;
      if (fields[5] === 'media-user-token' && fields[6] && fields[0].replace(/^\./, '') === 'music.apple.com') {
        hasMediaToken = true;
        tokenExpiry = Number(fields[4]) || 0;
      }
    }
  }
  const nowSec = Date.now() / 1000;
  const expired = hasMediaToken && tokenExpiry > 0 && tokenExpiry <= nowSec;
  return {
    valid: hasValidToken(content),
    exists: true,
    hasMediaToken,
    expired,
    expiresAt: tokenExpiry > 0 ? tokenExpiry * 1000 : null,
    count,
    path: cookiePath
  };
}

function normalizeCookieInput(rawInput) {
  const text = (rawInput || '').trim();
  if (!text) throw new Error('Cookie 内容不能为空');
  if (!text.includes('\t') && !text.startsWith('# Netscape')) {
    const cleaned = text.replace(/^media-user-token\s*=\s*/i, '').replace(/^["']|["']$/g, '').trim();
    if (cleaned.length < 16 || /[\t\r\n]/.test(cleaned)) {
      throw new Error('未识别到有效的 Netscape Cookie 或 media-user-token 令牌');
    }
    const exp = Math.floor(Date.now() / 1000) + 180 * 86400;
    return toNetscape([{
      domain: '.music.apple.com',
      path: '/',
      secure: true,
      expirationDate: exp,
      name: 'media-user-token',
      value: cleaned
    }]);
  }
  if (!hasValidToken(text)) {
    throw new Error('Cookie 内容中缺少有效的 .music.apple.com media-user-token 凭证（或已过期）');
  }
  return text.endsWith('\n') ? text : text + '\n';
}

module.exports = { validToken, toNetscape, hasValidToken, inspectCookieContent, normalizeCookieInput };
